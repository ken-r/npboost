def publication_model_fit_path(
    experiment_name: str,
    fixed_effect_name: str | None,
    task: Any,
    seed: int,
    model_names: str | Sequence[str],
    plot_root: str | Path | None = None,
    extension: str = "pdf",
    layout: str = "model_columns",
    prediction_style: str = "line",
) -> Path:
    """Return the standard publication path for a model-fit comparison figure.

    Args:
        task: Task object or task-name string; converted to the canonical
            lower-case underscore form used in saved artifacts.
        model_names: Single model name or sequence of names. Names are
            normalized, then joined with ``"-vs-"`` in the output filename.
        layout: String option used only in the filename:
            ``"model_columns"`` omits a layout suffix; ``"group_columns"`` adds
            the layout suffix used by row-wise model plots.
        prediction_style: String option used only in the filename:
            ``"interval"`` omits a style suffix; ``"line"`` and
            ``"interpolated_line"`` add a suffix matching the rendered style.
    """

    task_name = _normalize_task_name(task)
    model_slug = "-vs-".join(_normalize_model_names(model_names))
    layout_slug = "" if layout == "model_columns" else f"-{layout}"
    style_slug = "" if prediction_style == "line" else f"-{prediction_style}"
    if fixed_effect_name:
        filename = f"{fixed_effect_name}-{task_name}-{model_slug}{layout_slug}{style_slug}.{extension}"
    else:
        filename = f"{task_name}-{model_slug}{layout_slug}{style_slug}.{extension}"

    root = Path(plot_root) if plot_root is not None else PROJECT_ROOT / "plots" / "publication_model_fits"
    return root / experiment_name / filename


def load_model_fit_prediction_artifacts(
    experiment_name: str,
    model_name: str,
    task: Any,
    seed: int,
    fixed_effect_name: str | None = None,
    result_root: str | Path | None = None,
    splits: str | Sequence[str] = (VALIDATION_SPLIT_NAME, TEST_SPLIT_NAME),
) -> dict[str, pd.DataFrame]:
    """Load saved prediction artifacts for one fitted model.

    The files are expected to be created by ``scripts/experiments/save_model.py``
    next to the saved model. Synthetic experiments need ``fixed_effect_name``;
    real-data experiments leave it as ``None``.
    Returns a dictionary keyed by normalized split name.

    Args:
        task: Task object or task-name string. Normalized before locating files.
        splits: Split name or sequence of split names. Accepted strings are
            ``"validation"``/``"valid"``/``"val"`` and ``"test"``; case and
            hyphen/underscore differences are normalized.
    """

    task_name = _normalize_task_name(task)
    split_names = [_normalize_split_name(split) for split in _as_list(splits)]
    artifact_dir, artifact_stem = _model_fit_artifact_location(
        experiment_name=experiment_name,
        model_name=model_name,
        task_name=task_name,
        seed=seed,
        fixed_effect_name=fixed_effect_name,
        result_root=result_root,
    )

    frames: dict[str, pd.DataFrame] = {}
    for split_name in split_names:
        path = artifact_dir / f"{artifact_stem}-{split_name.lower()}-predictions.parquet"
        if not path.exists():
            raise FileNotFoundError(
                "Could not find saved predictions at "
                f"{path}. Refit the model with save_predictions=True first."
            )
        frame = pd.read_parquet(path)
        frame["model_name"] = _normalize_model_name(model_name)
        frame["model_label"] = _model_label(model_name)
        frame["prediction_split"] = split_name
        frame["prediction_path"] = str(path)
        frames[split_name] = frame

    return frames


def collect_model_fit_plot_data(
    experiment_name: str,
    model_names: str | Sequence[str],
    task: Any,
    seed: int,
    fixed_effect_name: str | None = None,
    response_name: str | None = None,
    split: str = TEST_SPLIT_NAME,
    feature: str | None = None,
    result_root: str | Path | None = None,
) -> tuple[pd.DataFrame, pd.DataFrame, str]:
    """Load predictions and split data, returning point and prediction frames.

    Returns ``(point_df, prediction_df, feature)``. ``point_df`` contains the
    observed context/support and target responses. ``prediction_df`` contains
    one row per model prediction with feature values and true responses attached.

    Args:
        model_names: Single model name or sequence of names. Each name is
            normalized before artifacts are loaded.
        task: Task object or task-name string. Supported names are
            ``"in_context"`` and ``"few_shot"``.
        split: Split to plot. Accepted strings are
            ``"validation"``/``"valid"``/``"val"`` and ``"test"``.
        feature: Feature column for the x-axis. If ``None``, the first
            non-special data column from the split data is used.
    """

    task_name = _normalize_task_name(task)
    split_name = _normalize_split_name(split)
    model_names = _normalize_model_names(model_names)
    split_df = load_model_fit_split_data(
        experiment_name=experiment_name,
        task=task_name,
        seed=seed,
        fixed_effect_name=fixed_effect_name,
        response_name=response_name,
    )
    feature = _resolve_feature(split_df, feature)

    context_df = _model_fit_context_frame(split_df, task_name, split_name)
    target_df = _model_fit_target_frame(split_df, task_name, split_name)
    point_df = _model_fit_point_frame(context_df, target_df, feature, task_name)

    prediction_frames = []
    for model_name in model_names:
        artifacts = load_model_fit_prediction_artifacts(
            experiment_name=experiment_name,
            model_name=model_name,
            task=task_name,
            seed=seed,
            fixed_effect_name=fixed_effect_name,
            result_root=result_root,
            splits=split_name,
        )
        prediction_frames.append(
            _attach_target_information(
                predictions=artifacts[split_name],
                target_df=target_df,
                feature=feature,
                model_name=model_name,
            )
        )

    if not prediction_frames:
        raise ValueError("At least one model name is required.")

    return point_df, pd.concat(prediction_frames, ignore_index=True), feature


def load_model_fit_split_data(
    experiment_name: str,
    task: Any,
    seed: int,
    fixed_effect_name: str | None = None,
    response_name: str | None = None,
) -> pd.DataFrame:
    """Load split data for a publication model-fit plot.

    Args:
        task: Task object or task-name string. The normalized task name selects
            the split-data subfolder.
        fixed_effect_name: Synthetic fixed-effect folder name. Leave as
            ``None`` for real-data plots.
        response_name: Real-data response variable folder. If omitted, exactly
            one matching split file must exist.
    """

    task_name = _normalize_task_name(task)
    if fixed_effect_name:
        path = (
            PROJECT_ROOT
            / "data"
            / "split"
            / "synthetic"
            / experiment_name
            / fixed_effect_name
            / task_name
            / f"seed{seed}.parquet"
        )
    else:
        if response_name is None:
            matches = list(
                (PROJECT_ROOT / "data" / "split" / "real" / experiment_name).glob(
                    f"*/{task_name}/seed{seed}.parquet"
                )
            )
            if len(matches) != 1:
                raise ValueError(
                    "For real-data plots, pass response_name unless exactly one "
                    f"split file matches {experiment_name!r}, {task_name!r}, seed {seed}."
                )
            path = matches[0]
        else:
            path = Path(
                RealDataLayout.get_split_df_path(
                    experiment_name=experiment_name,
                    response_var=response_name,
                    task=_TaskName(task_name),
                    seed=seed,
                )
            )

    if not path.exists():
        raise FileNotFoundError(f"Could not find split data at {path}.")
    return pd.read_parquet(path)


def plot_model_fit_prediction_columns(
    prediction_df: pd.DataFrame,
    *,
    point_df: pd.DataFrame,
    feature: str = "x",
    model_names: Sequence[str] | None = None,
    groups: Sequence[Any] | None = None,
    n_groups: int = 4,
    interval_level: float = 0.95,
    prediction_style: str = "line",
    layout: str = "model_columns",
    line_points: int = 300,
    prediction_color: str | None = None,
    interval_color: str | None = None,
    truth_color: str | None = None,
    point_color: str | None = None,
    truth_linestyle: str = ":",
    point_label: str = "context point",
    target_label: str = "target point",
    use_uniform_model_color: bool = True,
    show_context: bool = True,
    show_targets: bool | str = "auto",
    show_title: bool = False,
    title: str | None = None,
    y_label: str = "Response",
    show_group_metrics: bool = False,
    save_path: str | Path | None = None,
    show: bool = True,
    dpi: int = 300,
    legend_fontsize: float = 8.0,
    legend_handle_scale: float = 1.0,
    legend_ncol: int | None = None,
) -> tuple[Figure, np.ndarray]:
    """Plot model-fit predictions using the dense publication layout.

    ``prediction_df`` is the canonical model-fits frame. If it contains
    ``true_signal`` or ``true_fixed_effect``/``true_random_effect``, the latent
    truth line is drawn; otherwise real-data plots simply omit it.
    """

    if prediction_style == "smooth_line":
        prediction_style = "interpolated_line"
    if prediction_style not in {"interval", "line", "interpolated_line"}:
        raise ValueError("prediction_style must be 'interval', 'line', or 'interpolated_line'.")
    if layout not in {"model_columns", "group_columns"}:
        raise ValueError("layout must be either 'model_columns' or 'group_columns'.")
    if line_points < 2:
        raise ValueError("line_points must be at least 2.")

    required_prediction_columns = {"group_id", "model_name", "model_label", "mean", "std", feature}
    missing = required_prediction_columns - set(prediction_df.columns)
    if missing:
        raise ValueError(f"prediction_df is missing required columns: {sorted(missing)}")

    set_publication_style()
    prediction_color = prediction_color or MODEL_PREDICTION_COLOR
    interval_color = interval_color or MODEL_INTERVAL_COLOR
    truth_color = truth_color or MODEL_TRUTH_COLOR
    point_color = point_color or MODEL_POINT_COLOR
    render_targets = _should_show_model_fit_targets(show_targets, prediction_df)
    selected_groups = _select_model_fit_groups(prediction_df, groups=groups, n_groups=n_groups)
    model_names = (
        _normalize_model_names(model_names)
        if model_names is not None
        else list(dict.fromkeys(prediction_df["model_name"].astype(str)))
    )
    alpha = 1.0 - float(interval_level)
    z_score = NormalDist().inv_cdf(1 - alpha / 2)

    if layout == "model_columns":
        n_rows, n_cols = len(selected_groups), len(model_names)
        figsize = (2.65 * len(model_names), 1.85 * len(selected_groups) + 0.65)
    else:
        n_rows, n_cols = len(model_names), len(selected_groups)
        figsize = (2.65 * len(selected_groups), 1.85 * len(model_names) + 0.65)

    fig, axes_grid = plt.subplots(n_rows, n_cols, figsize=figsize, sharex=True, sharey=True, squeeze=False)
    axes = axes_grid.ravel()

    for group_index, group in enumerate(selected_groups):
        for model_index, model_name in enumerate(model_names):
            ax = axes_grid[group_index, model_index] if layout == "model_columns" else axes_grid[model_index, group_index]
            group_points = point_df[point_df["group_id"] == group]
            model_df = prediction_df[
                (prediction_df["group_id"] == group)
                & (prediction_df["model_name"] == model_name)
            ]

            if show_context:
                _draw_model_fit_points(ax, group_points, feature, "Context", color=point_color)
                _draw_model_fit_points(ax, group_points, feature, "Support", color=point_color)

            _draw_model_fit_truth(ax, model_df, feature, color=truth_color, linestyle=truth_linestyle)
            _draw_model_fit_predictions(
                ax=ax,
                model_df=model_df,
                feature=feature,
                model_name=model_name,
                model_index=model_index,
                x_offset=0.0,
                alpha=alpha,
                z_score=z_score,
                prediction_style=prediction_style,
                line_points=line_points,
                use_uniform_model_color=use_uniform_model_color,
                prediction_color=prediction_color,
                interval_color=interval_color,
            )

            if show_group_metrics and {"group_rmse", "group_crps"}.issubset(model_df.columns):
                _annotate_model_fit_group_metrics(ax, model_df)
            if render_targets:
                _draw_model_fit_points(ax, group_points, feature, "Target", color=truth_color)

            if layout == "model_columns":
                title_text = _model_label(model_name) if group_index == 0 else ""
                xlabel = _table_label(feature) if group_index == len(selected_groups) - 1 else ""
                ylabel = f"Task {group_index + 1}\n{y_label}" if model_index == 0 else ""
            else:
                title_text = f"Task {group_index + 1}" if model_index == 0 else ""
                xlabel = _table_label(feature) if model_index == len(model_names) - 1 else ""
                ylabel = f"{_model_label(model_name)}\n{y_label}" if group_index == 0 else ""
            _style_publication_axis(ax, title=title_text, xlabel=xlabel, ylabel=ylabel)

    _apply_model_fit_y_limits(axes, point_df, prediction_df, selected_groups, alpha, z_score)
    handles = _model_fit_legend_handles(
        prediction_df=prediction_df,
        point_df=point_df,
        model_names=model_names,
        show_context=show_context,
        show_targets=render_targets,
        prediction_style=prediction_style,
        alpha=alpha,
        use_uniform_model_color=use_uniform_model_color,
        legend_handle_scale=legend_handle_scale,
        point_label=point_label,
        target_label=target_label,
    )
    _place_publication_legend(
        fig,
        handles,
        title=title if show_title else None,
        ncol=legend_ncol or min(5, max(1, len(handles))),
        fontsize=legend_fontsize,
    )
    return _finish_figure(fig, save_path=save_path, show=show, dpi=dpi), axes


