"""Publication plotting helpers for synthetic data and saved model fits.

The file has two main workflows. 
1. Make compact figures for generated data: fixed effects, task realizations, components, and
train/validation/test splits. 
2. Load saved prediction artifacts and turn them into model-fit, coverage, and fixed-effect-estimation figures.

Model-fit artifacts are expected to contain at least ``mean`` and ``std``. When
available, saved interval columns such as ``lower_0.95`` and ``upper_0.95`` are
used directly; otherwise intervals are reconstructed from ``mean``/``std``.
For synthetic data, the artifacts should also carry truth columns if you want to visualize the true fixed/random/noise parts.
"""

