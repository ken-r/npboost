def _place_publication_legend(
    fig: Figure,
    handles: Sequence[Any],
    title: str | None = None,
    ncol: int | None = None,
    legend_y: float = 0.995,
    top: float = 0.94,
    fontsize: float | None = None,
    handlelength: float = 1.9,
) -> None:
    if title:
        fig.suptitle(title, x=0.5, ha="center", y=0.995, fontsize=10, fontweight="semibold")
        legend_y = min(legend_y, 0.94)
        top = min(top, 0.88)

    legend_kwargs = {}
    if fontsize is not None:
        legend_kwargs["fontsize"] = fontsize
    fig.legend(
        handles=handles,
        loc="upper center",
        bbox_to_anchor=(0.5, legend_y),
        ncol=ncol or min(5, max(1, len(handles))),
        frameon=False,
        handlelength=handlelength,
        columnspacing=1.0,
        **legend_kwargs,
    )
    _apply_publication_layout(fig, top=top)


def _apply_publication_layout(fig: Figure, top: float = 1.0) -> None:
    fig.tight_layout(rect=(0.0, 0.0, 1.0, top))


