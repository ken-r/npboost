def _table_label(value: Any | None) -> str | None:
    if value is None:
        return None

    text = str(value)
    if text in LABEL_OVERRIDES:
        return LABEL_OVERRIDES[text]

    cleaned = text.replace("_", " ").replace("-", " ")
    return cleaned[:1].upper() + cleaned[1:]


