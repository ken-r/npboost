def collect_publication_coverage_data(
    experiment_name: str,
    model_names: Sequence[str] = ("np", "npboost", "anp", "anpboost"),
    task_names: Sequence[str] = (IN_CONTEXT_TASK_NAME, FEW_SHOT_TASK_NAME),
    seed: int = 0,
    fixed_effect_name: str | None = None,
    response_name: str | None = None,
    split: str = TEST_SPLIT_NAME,
    nominal_levels: Sequence[float] = PUBLICATION_COVERAGE_LEVELS,
    result_root: str | Path | None = None,
) -> pd.DataFrame:
    """Compute saved-artifact coverage curves and MACE for publication plots.

    Coverage uses saved central interval quantiles when available. Older
    artifacts without quantile columns fall back to Gaussian ``mean``/``std``
    intervals.

    Args:
        model_names: Model-name strings to include in the calibration data.
        task_names: Task-name strings or task objects, typically
            ``"in_context"`` and ``"few_shot"``.
        split: Split to evaluate. Accepted strings are
            ``"validation"``/``"valid"``/``"val"`` and ``"test"``.
        nominal_levels: Coverage levels to check, e.g. ``0.95`` for a 95%
            interval.
    """

    rows = []
    split_name = _normalize_split_name(split)
    for task_name in [_normalize_task_name(task) for task in task_names]:
        _, prediction_df, _ = collect_model_fit_plot_data(
            experiment_name=experiment_name,
            model_names=model_names,
            task=task_name,
            seed=seed,
            fixed_effect_name=fixed_effect_name,
            response_name=response_name,
            split=split_name,
            result_root=result_root,
        )

        for model_name, model_df in prediction_df.groupby("model_name", sort=False):
            y_true = model_df["y_true"].to_numpy(dtype=float)
            model_rows = []
            for nominal in nominal_levels:
                nominal = float(nominal)
                lower, upper, interval_method = _prediction_interval_bounds(
                    model_df,
                    alpha=1.0 - nominal,
                )
                covered = (y_true >= lower) & (y_true <= upper)
                model_rows.append(
                    {
                        "task_name": task_name,
                        "task_label": _table_label(task_name),
                        "model_name": model_name,
                        "model_label": _model_label(model_name),
                        "nominal_coverage": nominal,
                        "empirical_coverage": float(np.mean(covered)),
                        "interval_method": interval_method,
                    }
                )

            mace = float(
                np.mean(
                    [
                        abs(row["empirical_coverage"] - row["nominal_coverage"])
                        for row in model_rows
                    ]
                )
            )
            for row in model_rows:
                row["mace"] = mace
            rows.extend(model_rows)

    return pd.DataFrame(rows)


def plot_publication_coverage_calibration(
    coverage_df: pd.DataFrame,
    model_names: Sequence[str] | None = None,
    task_names: Sequence[str] | None = None,
    use_uniform_model_color: bool = True,
    save_path: str | Path | None = None,
    show: bool = True,
    dpi: int = 300,
) -> tuple[Figure, np.ndarray]:
    """Plot empirical versus nominal coverage, one task row and model column per subplot.

    Each panel reports MACE, the mean absolute difference between empirical and
    nominal coverage over the plotted nominal levels. Curves below the diagonal
    indicate undercoverage; curves above it indicate overcoverage.
    """

    required = {"task_name", "model_name", "nominal_coverage", "empirical_coverage", "mace"}
    missing = required - set(coverage_df.columns)
    if missing:
        raise ValueError(f"coverage_df is missing required columns: {sorted(missing)}")

    set_publication_style()
    model_names = list(model_names or dict.fromkeys(coverage_df["model_name"].to_list()))
    task_names = list(task_names or dict.fromkeys(coverage_df["task_name"].to_list()))

    fig, axes_grid = plt.subplots(
        len(task_names),
        len(model_names),
        figsize=(2.7 * len(model_names), 2.35 * len(task_names) + 0.45),
        squeeze=False,
        sharex=True,
        sharey=True,
    )

    for row_index, task_name in enumerate(task_names):
        for col_index, model_name in enumerate(model_names):
            ax = axes_grid[row_index, col_index]
            panel_df = coverage_df[
                (coverage_df["model_name"] == model_name)
                & (coverage_df["task_name"] == task_name)
            ].sort_values("nominal_coverage")

            ax.plot(
                [0.0, 1.0],
                [0.0, 1.0],
                color=PUBLICATION_PALETTE["gray"],
                linestyle=":",
                linewidth=0.9,
            )
            if not panel_df.empty:
                color = _model_display_color(model_name, use_uniform_model_color)
                ax.plot(
                    panel_df["nominal_coverage"],
                    panel_df["empirical_coverage"],
                    marker="o",
                    markersize=3.2,
                    linewidth=1.1,
                    color=color,
                )
                ax.text(
                    0.05,
                    0.92,
                    f"MACE {panel_df['mace'].iloc[0]:.3f}",
                    transform=ax.transAxes,
                    fontsize=7.5,
                    color=PUBLICATION_PALETTE["black"],
                )

            _style_publication_axis(
                ax,
                title=_model_label(model_name) if row_index == 0 else "",
                xlabel="Nominal coverage" if row_index == len(task_names) - 1 else "",
                ylabel=f"{_table_label(task_name)}\nEmpirical coverage" if col_index == 0 else "",
            )
            ax.set_xlim(0.0, 1.0)
            ax.set_ylim(0.0, 1.0)

    _apply_publication_layout(fig)
    return _finish_figure(fig, save_path=save_path, show=show, dpi=dpi), axes_grid.ravel()


