def collect_publication_fixed_effect_estimation_data(
    experiment_name: str,
    model_names: Sequence[str] = ("npboost", "anpboost"),
    task_names: Sequence[str] = (IN_CONTEXT_TASK_NAME, FEW_SHOT_TASK_NAME),
    seed: int = 0,
    fixed_effect_name: str | None = None,
    response_name: str | None = None,
    split: str = TEST_SPLIT_NAME,
    feature: str | None = None,
    n_bins: int = 160,
    result_root: str | Path | None = None,
) -> pd.DataFrame:
    """Collect binned fixed-effect estimates and true fixed effects.

    The returned frame summarizes target-row predictions by feature bins, which
    makes the estimated global component readable for 1D synthetic fixed effects.

    Args:
        model_names: Model-name strings to compare.
        task_names: Task-name strings or task objects, typically
            ``"in_context"`` and ``"few_shot"``.
        split: Split to summarize. Accepted strings are
            ``"validation"``/``"valid"``/``"val"`` and ``"test"``.
        feature: Feature column to bin. If ``None``, the first non-special split
            data column is used.
        n_bins: Number of feature bins used to smooth the estimated fixed
            effect curves.
    """

    if n_bins < 2:
        raise ValueError("n_bins must be at least 2.")

    frames = []
    split_name = _normalize_split_name(split)
    for task_name in [_normalize_task_name(task) for task in task_names]:
        _, prediction_df, selected_feature = collect_model_fit_plot_data(
            experiment_name=experiment_name,
            model_names=model_names,
            task=task_name,
            seed=seed,
            fixed_effect_name=fixed_effect_name,
            response_name=response_name,
            split=split_name,
            feature=feature,
            result_root=result_root,
        )
        required = {"fixed_effect", "true_fixed_effect", selected_feature}
        missing = required - set(prediction_df.columns)
        if missing:
            raise ValueError(f"prediction artifacts are missing fixed-effect columns: {sorted(missing)}")

        bins = np.linspace(prediction_df[selected_feature].min(), prediction_df[selected_feature].max(), n_bins + 1)
        prediction_df = prediction_df.copy()
        prediction_df["x_bin"] = pd.cut(prediction_df[selected_feature], bins=bins, include_lowest=True)
        frame = (
            prediction_df.groupby(["model_name", "x_bin"], observed=True, sort=False)
            .agg(
                x=(selected_feature, "mean"),
                fixed_effect=("fixed_effect", "mean"),
                fixed_effect_q10=("fixed_effect", lambda values: values.quantile(0.10)),
                fixed_effect_q90=("fixed_effect", lambda values: values.quantile(0.90)),
                true_fixed_effect=("true_fixed_effect", "mean"),
            )
            .reset_index()
            .dropna(subset=["x", "fixed_effect", "true_fixed_effect"])
        )
        frame["task_name"] = task_name
        frame["task_label"] = _table_label(task_name)
        frame["feature"] = selected_feature
        frame["fixed_effect_abs_error"] = np.abs(frame["fixed_effect"] - frame["true_fixed_effect"])
        frame["fixed_effect_mae"] = frame.groupby("model_name", observed=True)["fixed_effect_abs_error"].transform("mean")
        frames.append(frame)

    return pd.concat(frames, ignore_index=True)


def plot_publication_fixed_effect_estimation(
    fixed_effect_df: pd.DataFrame,
    model_names: Sequence[str] | None = None,
    task_names: Sequence[str] | None = None,
    use_uniform_model_color: bool = True,
    save_path: str | Path | None = None,
    show: bool = True,
    dpi: int = 300,
) -> tuple[Figure, np.ndarray]:
    """Plot true and estimated fixed effects by task and model."""

    required = {"task_name", "model_name", "x", "fixed_effect", "fixed_effect_q10", "fixed_effect_q90", "true_fixed_effect"}
    missing = required - set(fixed_effect_df.columns)
    if missing:
        raise ValueError(f"fixed_effect_df is missing required columns: {sorted(missing)}")

    set_publication_style()
    model_names = list(model_names or dict.fromkeys(fixed_effect_df["model_name"].to_list()))
    task_names = list(task_names or dict.fromkeys(fixed_effect_df["task_name"].to_list()))
    feature_label = _table_label(fixed_effect_df["feature"].iloc[0] if "feature" in fixed_effect_df else "feature_0")

    fig, axes_grid = plt.subplots(
        len(task_names),
        len(model_names),
        figsize=(3.0 * len(model_names), 2.35 * len(task_names) + 0.45),
        squeeze=False,
        sharex=True,
        sharey=True,
    )

    for row_index, task_name in enumerate(task_names):
        for col_index, model_name in enumerate(model_names):
            ax = axes_grid[row_index, col_index]
            panel_df = fixed_effect_df[
                (fixed_effect_df["task_name"] == task_name)
                & (fixed_effect_df["model_name"] == model_name)
            ].sort_values("x")
            color = _model_display_color(model_name, use_uniform_model_color)

            if not panel_df.empty:
                x_values = panel_df["x"].to_numpy(dtype=float)
                lower = panel_df["fixed_effect_q10"].to_numpy(dtype=float)
                upper = panel_df["fixed_effect_q90"].to_numpy(dtype=float)
                ax.fill_between(x_values, lower, upper, color=color, alpha=0.12, linewidth=0)
                ax.plot(x_values, panel_df["fixed_effect"], color=color, linewidth=1.25, label="estimated fixed effect")
                ax.plot(
                    x_values,
                    panel_df["true_fixed_effect"],
                    color=PUBLICATION_PALETTE["black"],
                    linestyle=":",
                    linewidth=1.0,
                    label="true fixed effect",
                )
            _style_publication_axis(
                ax,
                title=_model_label(model_name) if row_index == 0 else "",
                xlabel=feature_label if row_index == len(task_names) - 1 else "",
                ylabel=f"{_table_label(task_name)}\nFixed effect" if col_index == 0 else "",
            )

    handles, labels = axes_grid[0, 0].get_legend_handles_labels()
    if handles:
        _place_publication_legend(fig, handles, ncol=2, legend_y=1.01, top=0.90)
    else:
        _apply_publication_layout(fig)
    return _finish_figure(fig, save_path=save_path, show=show, dpi=dpi), axes_grid.ravel()


def save_publication_fixed_effect_estimation(
    experiment_name: str,
    model_names: Sequence[str] = ("npboost", "anpboost"),
    task_names: Sequence[str] = (IN_CONTEXT_TASK_NAME, FEW_SHOT_TASK_NAME),
    seed: int = 0,
    fixed_effect_name: str | None = None,
    response_name: str | None = None,
    split: str = TEST_SPLIT_NAME,
    feature: str | None = None,
    n_bins: int = 160,
    result_root: str | Path | None = None,
    plot_root: str | Path | None = None,
    use_uniform_model_color: bool = True,
    show: bool = False,
    dpi: int = 300,
) -> tuple[Path, pd.DataFrame]:
    """Save a publication fixed-effect-estimation figure.

    Args:
        task_names: Task-name strings or task objects, typically
            ``"in_context"`` and ``"few_shot"``.
        split: Split to summarize. Accepted strings are
            ``"validation"``/``"valid"``/``"val"`` and ``"test"``.
        feature: Feature column to bin. If ``None``, the first non-special split
            data column is used.
        n_bins: Number of feature bins used to smooth the estimated fixed
            effect curves.
    """

    fixed_effect_df = collect_publication_fixed_effect_estimation_data(
        experiment_name=experiment_name,
        model_names=model_names,
        task_names=task_names,
        seed=seed,
        fixed_effect_name=fixed_effect_name,
        response_name=response_name,
        split=split,
        feature=feature,
        n_bins=n_bins,
        result_root=result_root,
    )
    plot_dir = Path(plot_root) if plot_root is not None else PROJECT_ROOT / "plots" / "publication_model_fits"
    prefix = f"{fixed_effect_name}-" if fixed_effect_name else ""
    save_path = plot_dir / experiment_name / f"{prefix}fixed-effect-estimation.pdf"
    fig, _ = plot_publication_fixed_effect_estimation(
        fixed_effect_df=fixed_effect_df,
        model_names=model_names,
        task_names=[_normalize_task_name(task) for task in task_names],
        use_uniform_model_color=use_uniform_model_color,
        save_path=save_path,
        show=show,
        dpi=dpi,
    )
    if not show:
        plt.close(fig)
    return save_path, fixed_effect_df
